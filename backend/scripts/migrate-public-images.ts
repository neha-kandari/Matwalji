// One-off script: uploads every image in frontend/public to Cloudinary and
// writes frontend/src/data/siteImages.ts with the resulting hosted URLs.
// Run with: npm run migrate-images
// Re-run it after replacing a file on disk (same public_id = same file gets
// overwritten in Cloudinary, so the generated URLs don't change).
import "dotenv/config";
import { v2 as cloudinary } from "cloudinary";
import { writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, "../../frontend");

const cloudName = process.env.CLOUDINARY_CLOUD_NAME;
const apiKey = process.env.CLOUDINARY_API_KEY;
const apiSecret = process.env.CLOUDINARY_API_SECRET;
if (!cloudName || !apiKey || !apiSecret) {
  throw new Error("Missing CLOUDINARY_CLOUD_NAME, CLOUDINARY_API_KEY or CLOUDINARY_API_SECRET (add them to .env)");
}
cloudinary.config({ cloud_name: cloudName, api_key: apiKey, api_secret: apiSecret, secure: true });

// key → source file relative to /public
const IMAGES: Record<string, string> = {
  favicon: "favicon.png",
  logo: "logo.png",
  hero: "hero.png",
  hero2: "hero2.png",
  ourHeritage: "ourHeritage.png",
  exclusiveYours: "exclusiveYours.png",
  exclusiveYoursMobile: "exclusiveYoursMobile.png",
  lehengaHero: "lehenga/Hero.png",
  lehengaShowcase1: "lehenga/lehenga.png",
  lehengaShowcase2: "lehenga/lehenga2.png",
  sareesHero: "sarees/Hero.png",
  sareesSilk: "sarees/silk.webp",
  sareesNet: "sarees/net.png",
  sareesNetWebp: "sarees/net.webp",
  sareesPremiumWebp: "sarees/premium.webp",
  aboutHero: "AboutHero.png",
  aboutUs: "aboutUs.png",
};

async function main() {
  const entries = Object.entries(IMAGES);
  const results: Record<string, string> = {};

  for (const [key, relPath] of entries) {
    const filePath = path.join(root, "public", relPath);
    const publicId = `matwalji/site/${key}`;
    const result = await cloudinary.uploader.upload(filePath, { public_id: publicId, overwrite: true });
    results[key] = result.secure_url;
    console.log(`${relPath} -> ${result.secure_url}`);
  }

  const lines = Object.entries(results).map(([key, url]) => `  ${key}: "${url}",`);
  const content = `// Generated by backend/scripts/migrate-public-images.ts — do not hand-edit the URLs.
// Re-run the script after replacing a file in frontend/public to refresh this file.
export const SITE_IMAGES = {
${lines.join("\n")}
} as const;
`;
  writeFileSync(path.join(root, "src/data/siteImages.ts"), content, "utf-8");
  console.log("\nWrote frontend/src/data/siteImages.ts");
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
